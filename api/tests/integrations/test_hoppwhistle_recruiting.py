@pytest.mark.asyncio
async def test_completion_posts_signed_to_the_recruiting_endpoint_and_never_echoes_the_token():
    node = {
        "id": "recruiting_reporting",
        "data": {
            "name": "R",
            "recruiting_base_url": BASE,
            "recruiting_signing_secret": SECRET,
        },
    }
    delivered = SimpleNamespace(ok=True, status_code=201, detail="delivered")
    with patch.object(
        completion_module, "deliver_report", AsyncMock(return_value=delivered)
    ) as deliver:
        results = await run_completion(
            [node],
            _context({"hr_session_id": "s1", "hr_session_token": "t1234567890123456"}),
        )
    kwargs = deliver.await_args.kwargs
    assert (
        kwargs["path"] == REPORT_PATH == "/api/internal/recruiting-voice/runs/complete"
    )
    assert kwargs["secret"] == SECRET and kwargs["base_url"] == BASE
    assert "t1234567890123456" not in json.dumps(results)
    assert results["hoppwhistle_recruiting_recruiting_reporting"]["delivered"] is True
