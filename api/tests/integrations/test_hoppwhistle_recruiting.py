# ── Inspection ──────────────────────────────────────────────────────────────


@pytest.mark.asyncio
async def test_inspection_reports_the_published_workflow_verbatim():
    definition = _resolved()
    tools = [
        SimpleNamespace(tool_uuid=f"uuid-{n}", name=n)
        for n in TOOL_NAMES
        if n != "end_interview"
    ]
    workflow = SimpleNamespace(
        id=7,
        workflow_uuid="wf-7",
        released_definition=SimpleNamespace(workflow_json=definition, version_number=3),
    )
    with (
        patch.object(
            inspect_module.db_client,
            "get_workflow_by_uuid",
            AsyncMock(return_value=workflow),
        ),
        patch.object(
            inspect_module.db_client,
            "get_tools_for_organization",
            AsyncMock(return_value=tools),
        ),
    ):
        result = await inspect_module.inspect_published_workflow("wf-7", 11)
    assert result["published_version"] == 3
    compliance = next(n for n in result["nodes"] if n["id"] == "compliance")
    original = next(n for n in definition["nodes"] if n["id"] == "compliance")
    assert compliance["prompt"] == original["data"]["prompt"]
    assert "save_interview_answer" in compliance["tool_names"]
    # A tool that no longer exists is reported, never silently dropped.
    assert result["unresolved_tool_uuids"] == ["uuid-end_interview"]
    assert {e["source"] for e in result["edges"]} >= {"intro", "background"}


