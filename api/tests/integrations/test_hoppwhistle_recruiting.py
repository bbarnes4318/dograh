def _context(initial_context: dict, **run_fields) -> IntegrationCompletionContext:
    run = SimpleNamespace(
        initial_context=initial_context,
        gathered_context=run_fields.pop(
            "gathered_context",
            {
                "call_disposition": "completed",
                "extracted_variables": {
                    "resident_state": "TX",
                    "hr_session_token": "leak",
                    "weekly_apps_submitted": 8,
                },
                "nodes_visited": ["intro", "background"],
                "end_call_reason": "interview complete",
            },
        ),
        usage_info={
            "call_duration_seconds": 900,
            "latency": {"avg_seconds": 0.9},
            "llm": {"m": {}},
        },
        transcript_text="assistant: Hi\nuser: Hello",
        recording_url="s3://bucket/rec.wav",
        transcript_url="s3://bucket/t.txt",
        workflow_id=42,
        created_at=datetime(2026, 11, 26, 15, 0, tzinfo=UTC),
        **run_fields,
    )
    return IntegrationCompletionContext(
        workflow_run_id=981,
        workflow_run=run,
        workflow_definition={},
        definition_id=1,
        organization_id=7,
        public_token="pub-token",
    )


def test_report_carries_conversation_facts_and_nothing_internal():
    report = build_report(
        _context({"hr_session_id": "s1", "hr_session_token": "t1234567890123456"})
    )
    assert report["contract_version"] == CONTRACT_VERSION
    assert report["session_id"] == "s1" and report["external_run_id"] == "981"
    assert report["extracted"] == {"resident_state": "TX", "weekly_apps_submitted": 8}
    assert report["nodes_visited"] == ["intro", "background"]
    assert report["latency_ms_avg"] == 900
    assert report["recording_url"].endswith("/pub-token/recording")
    assert report["voicemail"] is False


